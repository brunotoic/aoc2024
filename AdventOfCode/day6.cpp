std::vector<int> findGuard(std::vector<std::vector<char>> &grid) {
    int i, j;
    bool found = false;
    for (i = 0; i < grid.size() && !found; i++) {
        for (j = 0; j < grid[i].size() && !found; j++) {
            if (grid[i][j] == '^') {
            return std::vector<int>({i, j});
            }
        }
    }
}

int printGrid(std::vector<std::vector<char>> &grid) {
    for (const auto& row : grid) {
        for (char c : row) {
            std::cout << c;
        }
        std::cout << '\n';

    }
    std::cout << '\n';
    return 0;
}

int countX(std::vector<std::vector<char>> &grid) {
    int count = 0;
    for (const auto& row : grid) {
        count += std::count(row.begin(), row.end(), 'X');
    }
    return count;
}

